export const TECH_BY_ID: Record<string, Tech> = Object.fromEntries(TECHS.map((t) => [t.id, t]));

export const techOf = (id?: string | null) => (id ? TECH_BY_ID[id] : undefined);

/** Same-kind techs, alternatives first. */
export function swapCandidates(tech: Tech | undefined, kind: string): Tech[] {
  const same = TECHS.filter((t) => t.kind === kind && t.id !== tech?.id);
  const alt = new Set(tech?.alternatives ?? []);
  return [...same.filter((t) => alt.has(t.id)), ...same.filter((t) => !alt.has(t.id))];
}
