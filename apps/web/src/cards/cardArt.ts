// Card artwork: one icon per card, falling back to the card type's icon so a
// new card in cards.json renders without touching this file.

import {
  Archive,
  Inbox,
  TrendingUp,
  BellRing,
  Cpu,
  DatabaseZap,
  Dna,
  Globe,
  Receipt,
  Snail,
  Undo2,
  Volume2,
  Ban,
  BookOpen,
  Bug,
  Cable,
  ChevronsUp,
  CircleSlash,
  Coffee,
  Copy,
  FileCog,
  FileSearch,
  Fingerprint,
  Gauge,
  Hourglass,
  ListOrdered,
  ListPlus,
  Recycle,
  RefreshCw,
  Rocket,
  Server,
  ShieldCheck,
  Skull,
  Swords,
  Target,
  Timer,
  TrendingDown,
  Unplug,
  Wrench,
  Zap,
  type LucideIcon,
} from 'lucide-react';
import type { CardDef, CardType } from './types';

export const TYPE_ICON: Record<CardType, LucideIcon> = {
  infra: Server,
  policy: FileCog,
  action: Zap,
  attack: Swords,
  curse: Skull,
};

const CARD_ICON: Record<string, LucideIcon> = {
  scale_api: Server,
  replica: Copy,
  cache: Zap,
  timeout: Timer,
  backoff: Hourglass,
  breaker: Unplug,
  rate_limit: Gauge,
  burst: Rocket,
  stale: Archive,
  hotfix: Wrench,
  runbook: BookOpen,
  coffee: Coffee,
  block_ip: Ban,
  waf: ShieldCheck,
  honeypot: Target,
  index: ListOrdered,
  vertical: ChevronsUp,
  bigger_queue: ListPlus,
  load_shed: TrendingDown,
  pool: Cable,
  retry_budget: RefreshCw,
  captcha: Fingerprint,
  refactor: Recycle,
  postmortem: FileSearch,
  null_route: CircleSlash,
  rollback: Undo2,
  autoscaler: TrendingUp,
  queue: Inbox,
  geo_block: Globe,
  tarpit: Snail,
  tech_debt: Bug,
};

/** One icon per status (`statuses.json`). */
export const STATUS_ICON: Record<string, LucideIcon> = {
  adapted: Dna,
  noisy_neighbor: Volume2,
  cpu_credit: Cpu,
  replica_lag: DatabaseZap,
  bill_shock: Receipt,
  pager_fatigue: BellRing,
  geo_blocked: Globe,
  tarpit: Snail,
};

export const statusIcon = (id: string): LucideIcon => STATUS_ICON[id] ?? Bug;

export const cardIcon = (def: CardDef): LucideIcon => CARD_ICON[def.id.replace(/\+$/, '')] ?? TYPE_ICON[def.type];
